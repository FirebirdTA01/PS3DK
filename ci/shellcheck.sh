#!/usr/bin/env bash
# ci/shellcheck.sh — ShellCheck ratchet over scripts/**/*.sh  (v2)
#
# Independent implementation; does not reuse any third-party action YAML.
#
# The ratchet rule (tightened from v1):
#   The baseline records, for every (file, SCcode) pair, how many times
#   that code fires in that file. Each finding therefore has a COUNT, not
#   just a presence bit.
#     - a pair that fires now but is NOT in the baseline is NEW  -> FAIL
#     - a pair that fires MORE often now than the baseline count is a
#       REGRESSION -> FAIL
#       (this is the v1 hole: a new SC2086 in a file whose baseline
#        already had SC2086 used to pass silently; it now does not)
#     - a pair that fires the same number of times or fewer is allowed.
#       Fixing bugs to zero lets you delete the pair; shrinking a count
#       lets you lower it. The tree can only get cleaner.
#
# Fail-closed rule (tightened from v1):
#   The script captures shellcheck's exit status on the real run and
#   FAILS on anything above 1. In particular:
#     - exit 0: clean, no findings
#     - exit 1: one or more findings (normal; judged against the baseline)
#     - exit 2: usage / bad-option error
#     - exit 3: internal error (e.g. a file it could not parse)
#   v1 ran `set -u` only and never read the status, so an exit-2/3 run
#   (no SC codes in the output) reduced to "NEW is empty" and PASSED.
#   That fail-open path is closed here.
#
# Self-check (unchanged, keep it):
#   Before the real run the script points shellcheck at a scratch file
#   with a known unquoted variable and requires SC2086 to be reported. A
#   stubbed or too-old shellcheck that cannot see the bug is treated as
#   an installation failure, not a green pass.
#
# Format of ci/shellcheck-baseline.txt:
#   <whitespace-separated>  <file>  <SCcode>  <count>
#   one pair per line; count = occurrences of that code in that file,
#   generated by the pinned shellcheck at `-S style`. A different shellcheck
#   version may flag or fail to flag different rules, so pin the version
#   and the tarball's sha256 in the CI job (ci.yml does both).

set -u

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
BASELINE="ci/shellcheck-baseline.txt"

# --- Enumerate the check scope ------------------------------------------
if command -v find >/dev/null 2>&1; then
  FILES=$(find scripts -type f -name '*.sh' | sort)
else
  FILES=$(ls -1 scripts/*.sh 2>/dev/null | sort)
fi
if [ -z "$FILES" ]; then
  echo "FAIL: no scripts/**/*.sh found to check from $ROOT" >&2
  exit 1
fi

SC=$(command -v shellcheck)
if [ -z "$SC" ]; then
  echo "FAIL: shellcheck not on PATH" >&2
  exit 1
fi

# --- Self-check: shellcheck must be able to see the bug we care about ---
# `name='hello world'` is a valid assignment; `echo $name` is a valid use.
# Only SC2086 (unquoted variable) is in play here. The leading shebang keeps
# SC2148 out of the picture so the signal is not entangled with a version-
# and shell-target-dependent tip rule.
SCRATCH=$(mktemp)
cat >"$SCRATCH" <<'EOS'
#!/usr/bin/env bash
name='hello world'
echo $name
EOS
SELF_OUT=$("$SC" -f gcc "$SCRATCH" 2>&1)
SELF_RC=$?
rm -f "$SCRATCH"
if [ "$SELF_RC" -ne 1 ] || ! printf '%s\n' "$SELF_OUT" | grep -qE '\[SC2086\]'; then
  echo "FAIL: self-check blind — SC2086 not flagged on a known-bad scratch" >&2
  echo "     shellcheck exit=$SELF_RC" >&2
  echo "     shellcheck: $("$SC" --version 2>&1 | head -2 | tr '\n' ' ')" >&2
  exit 1
fi

# --- Real run: capture output AND exit status ----------------------------
OUT=$("$SC" -S style -f gcc -- $FILES 2>&1)
SC_RC=$?

# Fail-closed: the only statuses the baseline logic below is valid for are
# 0 (clean) and 1 (findings present). 2 (usage) and 3 (internal / parse)
# mean shellcheck could not produce a trustworthy finding set — do not let
# an empty finding list read as a green ratchet.
if [ "$SC_RC" -gt 1 ]; then
  echo "FAIL: shellcheck exited with status $SC_RC (could not be judged)" >&2
  echo "----- shellcheck output -----" >&2
  printf '%s\n' "$OUT" >&2
  echo "-----------------------------------" >&2
  exit 1
fi

# Normalize each finding to a `file<TAB>code` row (drop line/col) so that
# repeat findings of the same (file, code) stack up.
ROWS=$(printf '%s\n' "$OUT" \
  | sed -E 's|^([^:]+):[0-9]+:[0-9]+:.*\[(SC[0-9]+)\]$|\1\t\2|' \
  | grep -E $'\tSC[0-9]+' \
  | sort)

# Aggregate into `file<TAB>code<TAB>count` on the current tree.
# NF<2 next is the "clean tree" guard: when ROWS is empty the here-string
# still supplies one empty record; counting it would fabricate a
# (blank, blank) pair and report a false NEW, firing exactly when the
# ratchet reaches its goal. Skip records that are not a real pair.
if [ -z "$ROWS" ]; then
  CUR=""
else
  CUR=$(awk -F'\t' 'NF < 2 {next} { c[$1 "\t" $2]++ } END { for (k in c) printf "%s\t%d\n", k, c[k] }' <<<"$ROWS" | sort)
fi

# --- Baseline handling ----------------------------------------------------
if [ ! -e "$BASELINE" ]; then
  echo "FAIL: missing baseline at $BASELINE" >&2
  exit 1
fi
# Normalize the baseline the same way v1 did (split on any whitespace so a
# TAB-vs-space rewrite cannot defeat the comparison), and re-emit as
# `file<TAB>code<TAB>count`. Accept 2- or 3-field lines so an old
# (file, code) baseline still loads; a 2-field line means "count = 1".
BASE=$(awk '
  {
    line=$0
    sub(/^[ \t]+/, "", line)
    sub(/[ \t\r]+$/, "", line)
    if (line == "" || line ~ /^#/) next
    n = split(line, p, /[ \t]+/)
    if (n < 2) next
    if (p[2] !~ /^SC[0-9]+$/) next
    cnt = (n >= 3 && p[3] ~ /^[0-9]+$/) ? p[3] : 1
    print p[1] "\t" p[2] "\t" cnt
  }
' "$BASELINE" | sort)

# --- Compare: NEW pairs, REGRESSED counts, SHRUNK pairs -------------------
NEW=$(awk -v b="$(printf '%s' "$BASE")" -v c="$(printf '%s' "$CUR")" '
  BEGIN {
    nb = split(b, B, "\n")
    for (i = 1; i <= nb; i++) {
      m = split(B[i], f, "\t")
      if (m < 2 || f[1] == "" || f[2] == "") continue
      if (f[2] !~ /^SC[0-9]+$/) continue
      have[f[1] "\t" f[2]] = (m>=3 && f[3] ~ /^[0-9]+$/) ? f[3] : 1
    }
    nc = split(c, C, "\n")
    for (i = 1; i <= nc; i++) {
      m = split(C[i], f, "\t")
      if (m < 2 || f[1] == "" || f[2] == "") continue
      if (f[2] !~ /^SC[0-9]+$/) continue
      key = f[1] "\t" f[2]; cnt = (m>=3)?f[3]:"1"
      if (cnt !~ /^[0-9]+$/) cnt = "1"
      if (!(key in have)) print "NEW\t" key "\t" cnt "  (not in baseline)"
      else if (cnt > have[key]) print "REGRESSION\t" key "\t" cnt "  (baseline " have[key] ")"
      else if (cnt < have[key]) print "SHRUNK\t" key "\t" cnt "  (baseline " have[key] ")"
      else print "OK\t" key "\t" cnt
    }
  }
' <<<"$CUR")

# Report the informational shrink list first (it is not a failure).
SHRUNK=$(printf '%s\n' "$NEW" | awk -F'\t' '$1=="SHRUNK"{print $2"\t"$3}')
if [ -n "$SHRUNK" ]; then
  echo "ratchet: these baseline counts dropped — you may lower or delete them:"
  printf '%s\n' "$SHRUNK" | sed -n '1,4p' | sed 's/^/  - /'
  [ "$(printf '%s\n' "$SHRUNK" | grep -c .)" -gt 4 ] && echo "      …"
  echo
fi

FAILS=$(printf '%s\n' "$NEW" | awk -F'\t' '$1=="NEW" || $1=="REGRESSION"')

if [ -n "$FAILS" ]; then
  echo "FAIL: ShellCheck finding(s) newly introduced or growing beyond baseline"
  echo
  printf '%s\n' "$FAILS" | sed -E 's/^\t/  /'
  echo
  # Show the offending lines for actionability.  The FAILS row format is
  #   KIND <TAB> file <TAB> SCcode <TAB> count <TAB> (note)
  # so the code to display is the row's OWN code field — not a re-derived
  # "first code in this file" (which showed the wrong line when a file had
  # several baselined codes and a fourth was newly introduced).
  while IFS=$'\t' read -r kind pfile pcode pcnt _note; do
    [ -z "$pfile" ] && continue
    [ -z "$pcode" ] && continue
    printf '%s\n' "$OUT" \
      | grep -E "^${pfile//./\\.}:[0-9]+:[0-9]+:.*\[${pcode}\]" \
      | sed 's/^/    /' | head -20
  done <<<"$FAILS"
  echo
  echo "Fix the code (or add an inline '# shellcheck disable=SCxxxx' where"
  echo "idiomatic; the directive is already used for SC1090/SC1091 in"
  echo "scripts/). Then regenerate ci/shellcheck-baseline.txt — the counts"
  echo "may only stay equal or drop."
  exit 1
fi

NFIND=$(printf '%s\n' "$ROWS" | grep -c . || true)
NFILES=$(printf '%s\n' "$FILES" | grep -c . || true)
echo "shellcheck ratchet: ${NFILES} scripts, ${NFIND} finding(s) within baseline — green (shellcheck exit 0/1)."
