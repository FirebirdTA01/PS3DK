"""Embed the native dxt-example output without transforming its bytes."""
import hashlib
from pathlib import Path
import sys

if len(sys.argv) != 6:
    raise SystemExit("usage: generate-assets.py input.rgba tiles.dxt1 tiles.dxt3 tiles.dxt5 assets.h")
lines = ["/* Generated by tools/dxt-encoder/dxt-example; byte arrays are endian independent. */",
         "#include <stdint.h>"]
for arg, name, size in zip(sys.argv[1:5], ["rgba", "dxt1", "dxt3", "dxt5"], [256, 32, 64, 64]):
    data = Path(arg).read_bytes()
    if len(data) != size:
        raise SystemExit(f"{arg}: expected {size} bytes")
    lines += [f"/* {Path(arg).name} SHA256 {hashlib.sha256(data).hexdigest()} */",
              f"static const uint8_t sample_{name}[{size}] = {{"]
    lines += ["    " + ",".join(f"0x{x:02x}" for x in data[i:i+16]) + ","
              for i in range(0, len(data), 16)]
    lines += ["};"]
Path(sys.argv[5]).write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
