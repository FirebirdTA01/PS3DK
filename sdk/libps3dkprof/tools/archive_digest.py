#!/usr/bin/env python3
"""ARCHIVE-DIGEST-V1 of a profiler archive and its generated identity member (profile-format-spec.md 4, gate B2p).

usage: archive_digest.py digest ARCHIVE
       archive_digest.py emit ARCHIVE --id ID --premises N --kinds N   (prints prof_identity.c on stdout)
       archive_digest.py verify ARCHIVE [--id ID --premises N --kinds N]
Exit status: 0 success, 1 refused (the reason on stderr), 2 usage.

Message M: the 27 ASCII bytes "ps3dkprof.archive-digest.v1", one 0x00, u32 LE N (the members other than
prof_identity.o), then per member in increasing unsigned byte order of its name: u32 LE name length (1..255), the name,
the 32-byte SHA-256 of the member's bytes.  digest = SHA-256(M).  Refused: two members with one name, a name longer
than 255 bytes or containing '/', an archive that is not a GNU/System V `ar` archive; `emit` refuses an archive that
already holds prof_identity.o; `verify` needs exactly one prof_identity.o and compares the digest in it (found by its
16-byte marker) with the digest of the others, and prints the embedded identity (profile id, premise bits, kinds,
read in the byte order of the identity object's ELF header); with --id/--premises/--kinds it also refuses an
identity that differs from the one given (the build's declared values).  Symbol and long-name tables are not
members."""
import hashlib
import re
import struct
import sys

MAGIC = b'!<arch>\n'
IDENT = 'prof_identity.o'
MARKER = b'ps3dkprof.ident1'
PREFIX = b'ps3dkprof.archive-digest.v1\x00'


class Refused(Exception):
    pass


def members(path):
    """[(name, bytes)] in archive order (symbol tables and the long-name table excluded)."""
    data = open(path, 'rb').read()
    if not data.startswith(MAGIC):
        raise Refused(f'{path}: not an ar archive')
    pos, longnames, out = len(MAGIC), b'', []
    while pos < len(data):
        if pos + 60 > len(data):
            raise Refused(f'{path}: truncated member header at {pos}')
        h = data[pos:pos + 60]
        if h[58:60] != b'`\n':
            raise Refused(f'{path}: bad member header magic at {pos}')
        raw = h[0:16].rstrip(b' ')
        try:
            size = int(h[48:58].decode('ascii').strip())
        except ValueError:
            raise Refused(f'{path}: bad member size at {pos}') from None
        body = data[pos + 60:pos + 60 + size]
        if len(body) != size:
            raise Refused(f'{path}: truncated member at {pos}')
        pos += 60 + size + (size & 1)
        if raw in (b'/', b'/SYM64/'):
            continue
        if raw == b'//':
            longnames = body
            continue
        if raw.startswith(b'/') and raw[1:].isdigit():
            off = int(raw[1:])
            end = longnames.find(b'/\n', off)
            if end < 0:
                raise Refused(f'{path}: bad long-name reference {raw!r}')
            name = longnames[off:end]
        elif raw.endswith(b'/'):
            name = raw[:-1]
        else:
            name = raw
        out.append((name.decode('ascii', 'strict'), body))
    return out


def digest_of(ms):
    names = [n for n, _ in ms]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise Refused(f'duplicate member name(s): {dup}')
    rest = sorted((n, b) for n, b in ms if n != IDENT)
    msg = bytearray(PREFIX)
    msg += struct.pack('<I', len(rest))
    for n, b in sorted(rest, key=lambda x: x[0].encode('ascii')):
        nb = n.encode('ascii')
        if not 1 <= len(nb) <= 255 or b'/' in nb:
            raise Refused(f'member name {n!r} not allowed')
        msg += struct.pack('<I', len(nb)) + nb + hashlib.sha256(b).digest()
    return hashlib.sha256(bytes(msg)).digest()


def emit(ms, pid, premises, kinds):
    if any(n == IDENT for n, _ in ms):
        raise Refused(f'the input archive already holds {IDENT}')
    if not re.fullmatch(r'[A-Z][A-Z0-9-]{0,31}', pid):
        raise Refused(f'profile id {pid!r}: 1..32 bytes of A-Z 0-9 -, first a letter')
    if premises >> 11 or kinds == 0 or kinds & ~3:
        raise Refused('premise bits beyond 10, or kinds not in 1..3')
    d = digest_of(ms)
    digest = ', '.join(f'0x{x:02x}' for x in d)
    idc = ', '.join(f"'{c}'" for c in pid)
    return (
        '/* GENERATED by sdk/libps3dkprof/tools/archive_digest.py emit: do not edit.  ARCHIVE-DIGEST-V1 of the other\n'
        f' * members: {d.hex()} */\n'
        '#include "prof_identity.h"\n\n'
        'const ps3dk_prof__identity_t ps3dk_prof__identity = {\n'
        "    {'p', 's', '3', 'd', 'k', 'p', 'r', 'o', 'f', '.', 'i', 'd', 'e', 'n', 't', '1'},\n"
        f'    {{{digest}}},\n'
        f'    {premises}u,\n'
        f'    {kinds}u,\n'
        f'    {len(pid)}u,\n'
        f'    {{{idc}}},\n'
        '};\n'
    )


def embedded(ms):
    """(digest, profile id, premise bits, kinds) of the one identity member (ps3dk_prof__identity_t layout:
    marker[16] digest[32] premise_bits u32 kinds u32 id_len u8 id[32], no padding before id)."""
    ids = [b for n, b in ms if n == IDENT]
    if len(ids) != 1:
        raise Refused(f'{len(ids)} members named {IDENT} (want exactly 1)')
    obj = ids[0]
    at = obj.find(MARKER)
    if at < 0 or obj.find(MARKER, at + 1) >= 0:
        raise Refused(f'{IDENT}: the identity marker is absent or appears twice')
    if obj[:4] != bytes([0x7F]) + b'ELF' or obj[5] not in (1, 2):
        raise Refused(f'{IDENT}: not an ELF object with a known byte order')
    order = '<' if obj[5] == 1 else '>'
    body = obj[at:at + 89]
    if len(body) != 89:
        raise Refused(f'{IDENT}: the identity is truncated')
    premises, kinds = struct.unpack(order + 'II', body[48:56])
    n = body[56]
    if not 1 <= n <= 32:
        raise Refused(f'{IDENT}: id length {n}')
    try:
        pid = body[57:57 + n].decode('ascii', 'strict')
    except UnicodeDecodeError:
        raise Refused(f'{IDENT}: the profile id is not ASCII') from None
    return body[16:48], pid, premises, kinds


def main(argv):
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    cmd, path = argv[0], argv[1]
    try:
        ms = members(path)
        if cmd == 'digest' and len(argv) == 2:
            print(digest_of(ms).hex())
        elif cmd == 'verify' and (len(argv) == 2 or (len(argv) == 8 and argv[2::2] == ['--id', '--premises', '--kinds'])):
            want, (got, pid, premises, kinds) = digest_of(ms), embedded(ms)
            if want != got:
                raise Refused(f'embedded digest {got.hex()} != digest of the other members {want.hex()}')
            if len(argv) == 8:
                expect = (argv[3], int(argv[5], 0), int(argv[7], 0))
                if (pid, premises, kinds) != expect:
                    raise Refused(f'embedded identity {pid} premises {premises} kinds {kinds} != the declared '
                                  f'{expect[0]} premises {expect[1]} kinds {expect[2]}')
            print(f'verified {want.hex()} over {sum(1 for n, _ in ms if n != IDENT)} members; identity {pid} '
                  f'premises {premises} kinds {kinds}')
        elif cmd == 'emit' and len(argv) == 8 and argv[2::2] == ['--id', '--premises', '--kinds']:
            sys.stdout.write(emit(ms, argv[3], int(argv[5], 0), int(argv[7], 0)))
        else:
            print(__doc__, file=sys.stderr)
            return 2
    except (Refused, UnicodeDecodeError, OSError, ValueError) as e:
        print(f'archive_digest: refused: {e}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
