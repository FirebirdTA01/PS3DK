#!/usr/bin/env bash
# CellOS Lv-2 ABI conformance — implements docs/abi/cellos-lv2-abi-spec.md
# section 7, the parts that run without an emulator, and reports the rest.
#
# Section 7, emulator-independent parts, compared like with like:
#
#   7.1  build samples/toolchain/hello-ppu-abi-check with zero warnings and
#        have `abi-verify check` emit all PASS lines.
#        -> target: the freshly built, LINKED sample ELF (a final executable).
#        -> the linked sample is the real thing: abi-verify walks its .opd in
#           byte form (entry words resolved, exactly one constant TOC word,
#           every entry word inside an executable segment) and its
#           `.sys_proc_prx_param` block (size, magic, version, abi_version,
#           and the six ADDR32 descriptor slots) — the byte-level conformance
#           contract that the relocatable-startfile 7.2 cannot exercise.
#
#   7.2  diff the manifest of the INSTALLED PPU `lv2-crt0.o` (the REL startfile
#        that carries `.opd`) against tests/abi/fixtures/lv2-crt0.json on
#        every strict conformance field, AND the manifest of the INSTALLED
#        `lv2-sprx.o` (the REL startfile that carries `.sys_proc_prx_param`)
#        against tests/abi/fixtures/lv2-sprx.json.
#        -> those two objects are the toolchain's real link-time startfile
#           set (`scripts/build-runtime-lv2.sh` installs them, mirrored into
#           $PS3DK/ppu/lib/). The fixtures are generated by the same
#           `abi-verify manifest` command run against canonical startfile
#           outputs of the same shape, so the comparison is like-for-like.
#        -> strict conformance fields: ELF class / endian / machine / flags,
#           the full `.opd` descriptor shape on lv2-crt0.o (entry size,
#           descriptor count, and per-descriptor head/tail reloc type +
#           symbol — head against the function, tail against `.TOC.`), and the
#           full `.sys_proc_prx_param` block on lv2-sprx.o (size, magic,
#           version, abi_version, and the six R_PPC64_ADDR32 descriptor slots
#           at the fixed offsets).
#        -> deliberately NOT compared (object-specific, not conformance):
#           elf_type (REL vs REL, but the object is its own identity), os_abi
#           (untagged .o is 0x00, a final ELF 0x66), the per-symbol /
#           per-relocation / path tables (each startfile defines its own
#           symbols), and the concrete function symbol names that a head
#           R_PPC64_ADDR32 reloc points at — the SPECIFIC name is not an
#           invariant, only the R_PPC64_ADDR32 type + the descriptor layout
#           is. The concrete symbol names in the fixture table are informative,
#           not normative.
#
#   7.3  run the sample in RPCS3 (process start, exit-handler fire, clean
#        exit).  NOT done here — it needs an emulator — left to the hardware
#        pass.
#
# What it needs to run:
#   * the abi-verify binary ($PS3DEV/bin, $PS3DK/bin, or built from tools/ via
#     cargo automatically if missing);
#   * for 7.1: a native PPU toolchain + SDK to build the sample, or a
#     prebuilt sample ELF via --elf;
#   * for 7.2: the installed PPU lv2-crt0.o AND lv2-sprx.o (auto-located
#     under $PS3DEV/ppu or $PS3DK/ppu, or given via --crt0-obj / --sprx-obj).
#
# usage:
#   abi-conformance.sh [--ps3dev DIR] [--sdk DIR] [--abi-verify PATH]
#                      [--elf PATH] [--crt0-obj PATH] [--sprx-obj PATH]
#                      [--fixture-crt0 PATH] [--fixture-sprx PATH]
#                      [--sample DIR] [--build-dir DIR] [--no-build]
#                      [--report-only]
#
#   --elf PATH            7.1 target: this already-built linked sample (skip build).
#   --crt0-obj PATH       7.2 crt0 target: the lv2-crt0.o to diff against --fixture-crt0.
#   --sprx-obj PATH       7.2 sprx target: the lv2-sprx.o to diff against --fixture-sprx.
#   --fixture-crt0 PATH   the reference manifest for lv2-crt0.o (default
#                         tests/abi/fixtures/lv2-crt0.json).
#   --fixture-sprx PATH   the reference manifest for lv2-sprx.o (default
#                         tests/abi/fixtures/lv2-sprx.json).
#   --sample DIR          7.1 sample source (default samples/toolchain/hello-ppu-abi-check).
#   --build-dir DIR       CMake build dir for 7.1 (default: mktemp).
#   --no-build            do not build the 7.1 sample; --elf is then required.
#   --report-only         collect every FAIL but exit 0 with the finding(s) named,
#                         instead of failing the step.  Use while an ABI question
#                         is open so the gate surfaces it without blocking the
#                         release; drop the flag to make the same checks blocking
#                         once settled.
set -u

ps3dev="${PS3DEV:-}"
sdk="${PS3DK:-}"
abi_verify=""
elf=""          # 7.1 linked sample
crt0_obj=""     # 7.2 lv2-crt0.o
sprx_obj=""     # 7.2 lv2-sprx.o
sample=""
fixture_crt0=""
fixture_sprx=""
build_dir=""
build=1
report_only=0

while [ $# -gt 0 ]; do
    case "$1" in
        --ps3dev)        ps3dev="${2:?missing dir}"; shift 2 ;;
        --sdk)           sdk="${2:?missing dir}"; shift 2 ;;
        --abi-verify)    abi_verify="${2:?missing path}"; shift 2 ;;
        --elf)           elf="${2:?missing elf}"; shift 2 ;;
        --crt0-obj)      crt0_obj="${2:?missing path}"; shift 2 ;;
        --sprx-obj)      sprx_obj="${2:?missing path}"; shift 2 ;;
        --fixture-crt0)  fixture_crt0="${2:?missing path}"; shift 2 ;;
        --fixture-sprx)  fixture_sprx="${2:?missing path}"; shift 2 ;;
        --sample)        sample="${2:?missing dir}"; shift 2 ;;
        --build-dir)     build_dir="${2:?missing dir}"; shift 2 ;;
        --no-build)      build=0; shift ;;
        --report-only)   report_only=1; shift ;;
        -h|--help)       sed -n '2,70p' "$0"; exit 0 ;;
        *) echo "usage: $0 --help" >&2; exit 2 ;;
    esac
done

command -v python3 >/dev/null 2>&1 || { echo "python3 is required" >&2; exit 2; }
[ -n "$ps3dev" ] || { echo "PS3DEV not set (no PPU install prefix)" >&2; exit 2; }

sample="${sample:-$PWD/samples/toolchain/hello-ppu-abi-check}"
fixture_crt0="${fixture_crt0:-$PWD/tests/abi/fixtures/lv2-crt0.json}"
fixture_sprx="${fixture_sprx:-$PWD/tests/abi/fixtures/lv2-sprx.json}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail=0

step() { printf '\n== %s ==\n' "$*"; }
ok()   { printf '  [ok]   %s\n' "$*"; }
info() { printf '  [info] %s\n' "$*"; }
note_fail() {
    # A conformance FAIL.  Gates the run unless --report-only, in which case
    # it is surfaced (with the reason) so the section-7 deviation clause can
    # be applied, but does not block the release while the finding is open.
    printf '  [FAIL] %s\n' "$*"
    [ "$report_only" -eq 1 ] && printf '  [note] (report-only) open finding — named, not gating\n'
    fail=1
}

# ------------------------------------------------------------------ abi-verify
if [ -z "$abi_verify" ]; then
    for c in "$ps3dev/bin/abi-verify" "${sdk:-}/bin/abi-verify" "abi-verify"; do
        if [ -x "$c" ] || command -v "$c" >/dev/null 2>&1; then abi_verify="$c"; break; fi
    done
fi
if [ -z "$abi_verify" ]; then
    if command -v cargo >/dev/null 2>&1; then
        step "building abi-verify from tools/"
        if cargo build --release --manifest-path "$PWD/tools/Cargo.toml" -p abi-verify >/dev/null 2>&1 \
            || cargo build --release --workspace --manifest-path "$PWD/tools/Cargo.toml" >/dev/null 2>&1; then
            abi_verify="$PWD/tools/target/release/abi-verify"
        else
            echo "could not build abi-verify" >&2; exit 2
        fi
    else
        echo "no abi-verify found and cargo unavailable to build it" >&2; exit 2
    fi
fi
step "abi-verify: $abi_verify"
"$abi_verify" --version

# ---------------------------------------------- 7.1 — the linked sample ELF
if [ -z "$elf" ]; then
    if [ "$build" -ne 1 ]; then
        echo "7.1 needs a linked sample: pass --elf <sample> or allow the build" >&2; exit 2
    fi
    if [ ! -x "$ps3dev/ppu/bin/powerpc64-ps3-elf-gcc" ]; then
        echo "no native PPU gcc at $ps3dev/ppu/bin/powerpc64-ps3-elf-gcc" >&2
        echo "      build the native toolchain first, or pass --elf <sample> for 7.1" >&2
        exit 2
    fi
    command -v cmake >/dev/null 2>&1 || { echo "cmake is required to build the sample" >&2; exit 2; }
    build_dir="${build_dir:-$work/build}"
    step "7.1 — building $sample"
    if ! cmake -S "$sample" -B "$build_dir" -DCMAKE_TOOLCHAIN_FILE="$PWD/cmake/ps3-ppu-toolchain.cmake" \
             >"$work/cmake.log" 2>&1; then cat "$work/cmake.log" >&2; note_fail "sample cmake configure"; exit 1; fi
    if ! cmake --build "$build_dir" --verbose >"$work/build.log" 2>&1; then cat "$work/build.log" >&2; note_fail "sample build"; exit 1; fi
    if grep -E 'warning:' "$work/build.log" >/dev/null 2>&1; then
        note_fail "sample built with warnings (section 7.1 requires zero):"
        grep -E 'warning:' "$work/build.log" | sed 's/^/           /'
    else
        ok "sample built with zero warnings"
    fi
    elf="$(find "$build_dir" -maxdepth 1 -type f -name 'hello-ppu-abi-check' 2>/dev/null | head -n1)"
    [ -n "$elf" ] || elf="$(find "$build_dir" -maxdepth 2 -type f -name '*.elf' 2>/dev/null | head -n1)"
    if [ -z "$elf" ] || [ ! -f "$elf" ]; then
        note_fail "could not locate the built sample ELF"
        exit 1
    fi
    echo "  sample ELF: $elf"
else
    [ -f "$elf" ] || { echo "--elf $elf not found" >&2; exit 2; }
    ok "7.1 sample ELF (provided): $elf"
    info "7.1 sample was prebuilt: the zero-warning check is build-only and is not run here"
fi

if [ -n "$elf" ]; then
    step "7.1 — abi-verify check $elf (byte-level .opd / .sys_proc_prx_param / identity)"
    if "$abi_verify" check "$elf" >"$work/check.txt" 2>&1; then
        sed 's/^/  /' "$work/check.txt"
        ok "abi-verify check: all invariants PASS"
    else
        sed 's/^/  /' "$work/check.txt"
        note_fail "abi-verify check: invariants FAILED (see above)"
    fi
fi

# --------------------------------------- 7.2 — installed lv2-crt0.o + lv2-sprx.o
# The fixture manifests are themselves REL startfile outputs (lv2-crt0.o and
# lv2-sprx.o respectively); the like-for-like 7.2 targets are our INSTALLED
# lv2-crt0.o and lv2-sprx.o, which are what actually carry the .opd compact
# descriptors and the .sys_proc_prx_param block.  Both objects are installed
# by scripts/build-runtime-lv2.sh, mirrored into $PS3DK/ppu/lib.
rel_unavailable=0
if [ -z "$crt0_obj" ]; then
    crt0_obj="$(find "$ps3dev/ppu" "$sdk/ppu" -type f -name 'lv2-crt0.o' 2>/dev/null | grep -vE '/lp64/' | head -n1)"
fi
if [ -z "$sprx_obj" ]; then
    sprx_obj="$(find "$ps3dev/ppu" "$sdk/ppu" -type f -name 'lv2-sprx.o' 2>/dev/null | grep -vE '/lp64/' | head -n1)"
fi

# A per-object diff helper.  Takes: object path, fixture path, "crt0"|"sprx".
# The object's sections differ (crt0 -> .opd only; sprx -> .sys_proc_prx_param
# only), but the shared identity fields are always compared.
diff_one() {
    local obj="$1" fix="$2" role="$3"
    local obj_json fix_json
    obj_json="$work/$role.obj.json"
    fix_json="$work/$role.fix.json"
    if ! "$abi_verify" manifest "$obj" >"$obj_json" 2>"$work/$role.manifest.err"; then
        sed 's/^/  /' "$work/$role.manifest.err" >&2
        note_fail "$role manifest could not be read"
        return 1
    fi
    if [ ! -f "$fix" ]; then
        printf '  [FAIL] fixture %s not found (pass --fixture-%s, or check the tree)\n' "$fix" "$role"
        return 1
    fi
    cp -f "$fix" "$fix_json"

    # Locate the shared strict comparator (tests/abi/abifx.py) relative to this
    # script, so it works regardless of the CWD the caller used.  The old
    # inline Python here collapsed the descriptor table into a set() and
    # sorted() it, which crashed when a symbol was present in one manifest and
    # None in the other, and let a duplicate descriptor slip past.  abifx.py
    # compares descriptor-by-descriptor (count, layout, addend) and treats
    # the concrete head/tail symbol names as informative, not contract.
    local script_dir repo_root abifx
    script_dir="$(cd "$(dirname "$0")" && pwd)"
    repo_root="$(cd "$script_dir/.." && pwd)"
    abifx="$repo_root/tests/abi/abifx.py"
    if [ ! -f "$abifx" ]; then
        printf '  [FAIL] comparator not found: %s\n' "$abifx"
        return 1
    fi
    python3 "$abifx" compare "$obj_json" "$fix_json" "$role"
    return $?
}

crt0_unavailable=0
sprx_unavailable=0

if [ -n "$crt0_obj" ] && [ -f "$crt0_obj" ]; then
    step "7.2a — manifest of $crt0_obj vs $fixture_crt0 (ELF identity + .opd descriptor shape)"
    if diff_one "$crt0_obj" "$fixture_crt0" "crt0"; then
        ok "lv2-crt0.o matches the fixture on the strict conformance fields"
    else
        note_fail "lv2-crt0.o manifest diff — fields flagged above"
    fi
else
    crt0_unavailable=1
    printf '  [FAIL] 7.2a UNAVAILABLE: no installed PPU lv2-crt0.o found under %s/ppu (or --crt0-obj)\n' "$ps3dev"
    printf '         the .opd REL-vs-fixture comparison could not run.\n'
    printf '         strict mode must fail on a missing required input; it does NOT pass.\n'
fi

if [ -n "$sprx_obj" ] && [ -f "$sprx_obj" ]; then
    step "7.2b — manifest of $sprx_obj vs $fixture_sprx (ELF identity + .sys_proc_prx_param block)"
    if diff_one "$sprx_obj" "$fixture_sprx" "sprx"; then
        ok "lv2-sprx.o matches the fixture on the strict conformance fields"
    else
        note_fail "lv2-sprx.o manifest diff — fields flagged above"
    fi
else
    sprx_unavailable=1
    printf '  [FAIL] 7.2b UNAVAILABLE: no installed PPU lv2-sprx.o found under %s/ppu (or --sprx-obj)\n' "$ps3dev"
    printf '         the .sys_proc_prx_param REL-vs-fixture comparison could not run.\n'
    printf '         strict mode must fail on a missing required input; it does NOT pass.\n'
fi

# ---------------------------------------------------------------- final verdict
# The 7.2 REL-vs-REL comparison is a required input.  If EITHER object could
# not run (no installed lv2-crt0.o or lv2-sprx.o), a strict run must FAIL
# outright — it cannot pass on the linked-sample half alone (7.1).  A
# report-only run may exit 0, but it says UNAVAILABLE rather than PASS, so a
# green run is never mistaken for one that actually checked a REL object.
printf '\n== %s ==\n' "abi-conformance verdict"
if [ "$crt0_unavailable" -eq 1 ] || [ "$sprx_unavailable" -eq 1 ]; then
    echo "UNAVAILABLE — one or both 7.2 objects (lv2-crt0.o, lv2-sprx.o) could not run:"
    [ "$crt0_unavailable" -eq 1 ] && echo "  - lv2-crt0.o  (not found under $ps3dev/ppu and none supplied via --crt0-obj)"
    [ "$sprx_unavailable" -eq 1 ] && echo "  - lv2-sprx.o  (not found under $ps3dev/ppu and none supplied via --sprx-obj)"
    if [ "$report_only" -eq 1 ]; then
        echo "         Report-only: not blocking, but this is NOT a pass — the REL-vs-fixture"
        echo "         check has not been performed on the missing startfile(s).  Supply the"
        echo "         installed $ps3dev/ppu lv2-crt0.o / lv2-sprx.o (or --crt0-obj / --sprx-obj)"
        echo "         before treating section 7.2 as satisfied."
        exit 0
    fi
    echo "         Strict mode requires both REL objects; they are required inputs, so the"
    echo "         run fails rather than passing on unverified ground."
    exit 1
fi
if [ "$fail" -eq 0 ]; then
    echo "PASS — 7.1 (linked sample zero-warnings + abi-verify all-PASS byte-level)"
    echo "       and 7.2 (installed lv2-crt0.o + lv2-sprx.o vs fixture strict fields)"
    echo "       hold.  7.3 (RPCS3 run) remains a manual step."
    exit 0
elif [ "$report_only" -eq 1 ]; then
    echo "REPORT — one or more section-7 conformance fields are flagged (named above)."
    echo "         Report-only gate: the finding is surfaced, not blocking, so the"
    echo "         section-7 deviation clause (fixture update with rationale, or a"
    echo "         toolchain/abi-verify change) can be applied before this goes strict."
    exit 0
else
    echo "FAIL — one or more section-7 conformance invariants do not hold."
    echo "         Per the spec, a deviation requires either a fixture update with"
    echo "         documented rationale or a change to abi-verify with a regression test."
    exit 1
fi
