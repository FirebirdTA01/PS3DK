/* the four mul() integration twins (role control-binder-matrix, bit-exact pairs) */
#define F32_MATRIX_NTWINS 4
static const char *const f32_matrix_twins[F32_MATRIX_NTWINS] = {
	"binder_matrix_0", "binder_matrix_1", "binder_matrix_2", "binder_matrix_3"
};
#define F32_MATRIX_NMEMBERS (F32_MATRIX_NRECIPES + F32_MATRIX_NTWINS)

static const f32_matrix_recipe *f32_matrix_recipe_find(const char *role, const char *name)
{
	for (int i = 0; i < F32_MATRIX_NRECIPES; i++)
		if (strcmp(f32_matrix_recipes[i].name, name) == 0 && strcmp(f32_matrix_recipes[i].role, role) == 0)
			return &f32_matrix_recipes[i];
	return 0;
}

/* The normal (unfaulted) words of a recipe's row: those of its probe. */
static const uint32_t *f32_matrix_normal_words(const f32_matrix_recipe *m)
{
	char probe[32];
	static const char *const tag[4] = { "44", "33", "34", "43" };
	snprintf(probe, sizeof(probe), "mprobe_%s_r%d", tag[m->shape], m->row);
	const f32_matrix_recipe *p = f32_matrix_recipe_find("control-binder-matrix-probe", probe);
	return p ? p->expect : 0;
}

/* Manifest fields of a matrix control row, checked against its pinned recipe:
 * expect= is required, normal= is required for a negative and forbidden for a probe;
 * pinned words must match exactly (a skip-row member's expect is checked by the guest
 * against the container).  Returns 1 if the row may run. */
static int f32_matrix_fields_ok(const char *role, const char *name,
                                int has_expect, const uint32_t expect[4],
                                int has_normal, const uint32_t normal[4])
{
	const f32_matrix_recipe *m = f32_matrix_recipe_find(role, name);
	if (!m || !has_expect)
		return 0;
	const int neg = strcmp(role, "control-binder-matrix-neg") == 0;
	if (neg != (m->fault != 0) || has_normal != neg)
		return 0;
	if (m->has_expect && memcmp(expect, m->expect, sizeof(m->expect)) != 0)
		return 0;
	if (neg) {
		const uint32_t *nw = f32_matrix_normal_words(m);
		if (!nw || memcmp(normal, nw, 4 * sizeof(uint32_t)) != 0)
			return 0;
		if (memcmp(expect, normal, 4 * sizeof(uint32_t)) == 0)
			return 0;   /* a negative must predict words distinct from the normal probe */
	}
	return 1;
}

/* member index of a matrix control (recipes, then twins), or -1 */
static int f32_matrix_member(const char *role, const char *name)
{
	for (int i = 0; i < F32_MATRIX_NRECIPES; i++)
		if (strcmp(f32_matrix_recipes[i].name, name) == 0 && strcmp(f32_matrix_recipes[i].role, role) == 0)
			return i;
	if (strcmp(role, "control-binder-matrix") == 0)
		for (int i = 0; i < F32_MATRIX_NTWINS; i++)
			if (strcmp(f32_matrix_twins[i], name) == 0)
				return F32_MATRIX_NRECIPES + i;
	return -1;
}

static int f32_is_matrix_role(const char *role)
{
	return strcmp(role, "control-binder-matrix-probe") == 0 || strcmp(role, "control-binder-matrix-neg") == 0 ||
	       strcmp(role, "control-binder-matrix") == 0;
}

typedef struct {
	int invalid;                  /* latched: a control failed or was missing */
	int passed[F32_GATE_NREQ];    /* required controls seen passing */
	int checked;                  /* the required set was checked (first corpus row) */
	int corpus_mismatch;          /* corpus rows that judged mismatch */
	uint32_t matrix_passed;       /* bit i: matrix member i passed */
	char first_failure[96];       /* the first control that invalidated the run */
} f32_gate;

static void f32_gate_init(f32_gate *g)
{
	memset(g, 0, sizeof(*g));
}

/* The required-control key a control row satisfies, or -1. */
static int f32_gate_key(const char *role, const char *name)
{
	if (strcmp(role, "control-f32-k") == 0) {
		for (int q = 0; q < 4; q++)
			if (strcmp(name, f32_gate_required[q]) == 0)
				return q;
		return -1;
	}
	if (strcmp(role, "control-f32-xy") == 0) return 4;
	if (strcmp(role, "control-f32-frames") == 0) return 5;
	for (int q = 6; q < F32_GATE_NREQ; q++)
		if (strcmp(role, f32_gate_required[q]) == 0)
			return q;
	return -1;
}

static void f32_gate_fail(f32_gate *g, const char *what)
{
	if (!g->invalid) {
		size_t n = strlen(what);
		if (n >= sizeof(g->first_failure)) n = sizeof(g->first_failure) - 1;
		memcpy(g->first_failure, what, n);
		g->first_failure[n] = 0;
	}
	g->invalid = 1;
}

/* Record a control row's outcome.  A pass never clears an earlier failure. */
static void f32_gate_control(f32_gate *g, const char *role, const char *name, int passed)
{
	if (!passed) {
		f32_gate_fail(g, name);
		return;
	}
	int k = f32_gate_key(role, name);
	if (k >= 0)
		g->passed[k] = 1;
}

#define F32_GATE_NCORE 6

static void f32_gate_require(f32_gate *g, int n)
{
	for (int q = 0; q < n; q++)
		if (!g->passed[q])
			f32_gate_fail(g, f32_gate_required[q]);
}

/* Called before each corpus row: 1 if it may be judged.  The first call
 * checks that EVERY required control, core and binding, ran and passed. */
static int f32_gate_corpus_allowed(f32_gate *g)
{
	if (!g->checked) {
		g->checked = 1;
		f32_gate_require(g, F32_GATE_NREQ);
	}
	return !g->invalid;
}

/* A row's raw images did not reach their files (open, short write or
 * close failed).  The host comparator judges those files, so the run is
 * latched INVALID - for a control and for a corpus row alike - while the
 * row's own comparison stays recorded and counted. */
static void f32_gate_artifact_failed(f32_gate *g, const char *name)
{
	char what[96];
	snprintf(what, sizeof(what), "artifact-write:%s", name);
	f32_gate_fail(g, what);
}

/* A matrix control may run only after the core and binding controls passed; one
 * that comes earlier, or fails, latches INVALID.  A pass sets only its own member
 * bit, so duplicates never fill a missing member. */
static int f32_gate_matrix_prereq_ok(const f32_gate *g)
{
	for (int q = 0; q < F32_GATE_NREQ; q++)
		if (!g->passed[q]) return 0;
	return !g->invalid;
}

static void f32_gate_matrix_control(f32_gate *g, const char *role, const char *name, int passed)
{
	int m = f32_matrix_member(role, name);
	if (m < 0 || !passed || !f32_gate_matrix_prereq_ok(g)) {
		f32_gate_fail(g, name);
		return;
	}
	g->matrix_passed |= 1u << m;
}

/* every named matrix member passed and the run is still valid */
static int f32_gate_matrix_ready(const f32_gate *g)
{
	const uint32_t all = (F32_MATRIX_NMEMBERS >= 32) ? 0xFFFFFFFFu : ((1u << F32_MATRIX_NMEMBERS) - 1u);
	return !g->invalid && g->matrix_passed == all;
}

static void f32_gate_corpus_result(f32_gate *g, int mismatch)
{
	g->corpus_mismatch += mismatch ? 1 : 0;
}

/* End of run.  A controls-only manifest (no corpus row: a qualification of
 * the float path itself) needs the six core controls; the binding controls
 * are required once a corpus row is judged (checked above). */
static int f32_gate_exit(f32_gate *g)
{
	if (!g->checked)
		f32_gate_require(g, F32_GATE_NCORE);
	return g->invalid ? 2 : (g->corpus_mismatch ? 1 : 0);
}

static const char *f32_gate_verdict(int exit_code)
{
	return exit_code == 2 ? "SHADER_DIFF_INVALID" : exit_code == 1 ? "SHADER_DIFF_FAIL" : "SHADER_DIFF_OK";
}

/* ---- row refusal (codex review of f37d5f41) ----
 * Float mode judges colour 0 only, through the plain 2D binder and scalar
 * auto uniforms.  Applied to EVERY row - controls included - before any
 * special case: a row is refused (never drawn, never silently narrowed)
 * when either container declares an output other than COLOR0 or replaces
 * depth, when the row names its own vertex program, when it asks for
 * extra judged outputs (judge=), or when a container needs a binder kind
 * float mode has no proving set for (binder mask bits: RECT=1 CUBE=2
 * 3D=4 matrix=8).  Returns the refusal status, or NULL. */
static const char *f32_row_refusal(int color_mask_a, int color_mask_b, int depth_a, int depth_b,
                                   int has_vp, int judge_extra, unsigned binder_mask,
                                   int matrix_admitted, int matrix_ready, int is_matrix_control)
{
	if (judge_extra) return "f32-judge-unsupported";
	if (has_vp) return "f32-vp-unsupported";
	if (color_mask_a != 1 || color_mask_b != 1 || depth_a || depth_b) return "f32-outputs-unsupported";
	/* RECT / CUBE / 3D: never admitted, for any row, controls included */
	if (binder_mask & 7u) return "f32-binder-unsupported";
	/* a matrix: a matrix control waives only its OWN matrix requirement; any other
	 * row needs every matrix it declares to be a plain float4x4/float3x3
	 * (matrix_admitted) and the complete matrix set to have passed (matrix_ready) */
	if ((binder_mask & 8u) && !is_matrix_control) {
		if (!matrix_admitted) return "f32-binder-unsupported";
		if (!matrix_ready) return "f32-matrix-unqualified";
	}
	return 0;
}

/* ---- pinned core control recipes ----
 * The four named core k controls carry FIXED words; the manifest's ka/kb
 * must equal them exactly, so an edited manifest (identical zero words,
 * no NaN, no ULP step) cannot make them pass without measuring anything.
 * A k control under any other name is not a core control. */
typedef struct { const char *name; uint32_t ka[4], kb[4]; } f32_k_recipe;
static const f32_k_recipe f32_k_recipes[4] = {
	{ "f32-words", { 0x3f000000u, 0xbfc00000u, 0x40490fdbu, 0x00000000u },
	               { 0x3f000000u, 0xbfc00000u, 0x40490fdbu, 0x00000000u } },
	{ "f32-ulp",   { 0x3f000000u, 0x3f000000u, 0x3f000000u, 0x3f000000u },
	               { 0x3f000001u, 0x3f000000u, 0x3f000000u, 0x3f000000u } },
	{ "f32-sub8",  { 0x3f000000u, 0x3f000000u, 0x3f000000u, 0x3f000000u },
	               { 0x3f004000u, 0x3f000000u, 0x3f000000u, 0x3f000000u } },
	{ "f32-nan",   { 0x7fc00000u, 0x3f800000u, 0x7fc00001u, 0xc0000000u },
	               { 0x7fc00000u, 0x3f800000u, 0x7fc00001u, 0xc0000000u } },
};

/* 1 if the row may run as a core control: a named core control must carry
 * its recipe's words exactly; any other k-control name passes through. */
static int f32_k_recipe_ok(const char *name, const uint32_t ka[4], const uint32_t kb[4])
{
	for (int i = 0; i < 4; i++)
		if (strcmp(name, f32_k_recipes[i].name) == 0)
			return memcmp(ka, f32_k_recipes[i].ka, sizeof(f32_k_recipes[i].ka)) == 0 &&
			       memcmp(kb, f32_k_recipes[i].kb, sizeof(f32_k_recipes[i].kb)) == 0;
	return 1;
}

