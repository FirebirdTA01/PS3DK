#!/usr/bin/env python3
"""Float-mode matrix-binder controls (design r3, codex-approved 2026-10-19 23:00).

Generates the probe, negative and integration-twin controls for plain float4x4
and float3x3 (plus 3x4/4x3 stride coverage) automatic matrix uniforms, with the
expected raw binary32 words computed HERE from the auto-matrix rule, written
from its definition (independent of the guest's code):

    h  = FNV-1a 32-bit of the parameter name
    x  = (h ^ (k * 0x9E3779B1)) * 0x85EBCA6B (mod 2^32); x ^= x >> 13
    a  = 0.125 + (x >> 9) / 2^24                      (k = 4*row + column)
    element(r, c) = a + 0.375 on the diagonal, (a - 0.375) * 0.25 elsewhere

Every value is an exact binary32 (checked), so no rounding is assumed.

usage:
  f32_matrix_controls.py --recipes            print the C recipe and twin tables for f32_gate.h
  f32_matrix_controls.py --check HEADER       exit 1 unless HEADER's tables equal the computed ones
  f32_matrix_controls.py --stage COMPILER OUT print manifest rows; write sources + containers to OUT/controls
"""
import struct
import subprocess
import sys
from pathlib import Path

NAME = 'u_matrix'
PAD = 0x40200000          # 2.5: the literal pad lane of a 3-wide probe row (no element can equal it)
SHAPES = {'44': (4, 4), '33': (3, 3), '34': (3, 4), '43': (4, 3)}   # rows x columns
ADMITTED = ('44', '33')   # the shapes whose rows the gate admits; 34/43 are stride coverage only
TWINS = ('33', '44', '34', '43')   # binder_matrix_0..3: the mul() integration twins, by shape


def fnv1a(s):
    h = 2166136261
    for ch in s.encode():
        h = ((h ^ ch) * 16777619) & 0xFFFFFFFF
    return h


def f32w(v):
    w = struct.unpack('>I', struct.pack('>f', v))[0]
    assert struct.unpack('>f', struct.pack('>I', w))[0] == v, 'not exact in binary32: %r' % v
    return w


def element(r, c):
    x = (fnv1a(NAME) ^ ((4 * r + c) * 0x9E3779B1)) & 0xFFFFFFFF
    x = (x * 0x85EBCA6B) & 0xFFFFFFFF
    x ^= x >> 13
    a = 0.125 + (x >> 9) / 16777216.0
    return f32w(a + 0.375 if r == c else (a - 0.375) * 0.25)


def row_words(shape, r, get=element):
    rows, cols = SHAPES[shape]
    w = [get(r, c) for c in range(cols)]
    return w + [PAD] * (4 - cols)


def recipes():
    """(name, role, shape, row, fault, fault_r, fault_c, expect) for every pinned member.
    fault 0 none, 1 transpose (square shapes only), 2 skip-row, 3 ulp(+1) at (fault_r, fault_c).
    A skip-row expectation is not computable from the rule: it is the container's embedded
    words for that row, pinned by --stage and re-derived by the guest from the same bytes."""
    out = []
    for shape in ('44', '33', '34', '43'):
        for r in range(SHAPES[shape][0]):
            out.append(('mprobe_%s_r%d' % (shape, r), 'control-binder-matrix-probe', shape, r, 0, 0, 0, row_words(shape, r)))
    for shape in ADMITTED:
        n = SHAPES[shape][0]
        tw = row_words(shape, 1, get=lambda r, c: element(c, r))     # square: (r,c) <- (c,r), in range
        out.append(('mneg_%s_transpose' % shape, 'control-binder-matrix-neg', shape, 1, 1, 0, 0, tw))
        out.append(('mneg_%s_skip_r1' % shape, 'control-binder-matrix-neg', shape, 1, 2, 1, 0, None))
        uw = row_words(shape, 1)
        uw[2] = (uw[2] + 1) & 0xFFFFFFFF                             # element (1,2) +1 ULP, raw word
        out.append(('mneg_%s_ulp_1_2' % shape, 'control-binder-matrix-neg', shape, 1, 3, 1, 2, uw))
        assert n >= 3
    for name, role, shape, r, fault, fr, fc, exp in out:
        if fault in (1, 3):
            assert exp != row_words(shape, r), name + ': the fault must change a read-back word'
    return out


def c_table():
    lines = ['/* GENERATED by f32_matrix_controls.py --recipes; checked by f32-gate-test.sh. */',
             '#define F32_MATRIX_NRECIPES %d' % len(recipes()),
             'static const f32_matrix_recipe f32_matrix_recipes[F32_MATRIX_NRECIPES] = {']
    for name, role, shape, r, fault, fr, fc, exp in recipes():
        e = '{ 0, 0, 0, 0 }' if exp is None else '{ ' + ', '.join('0x%08xu' % w for w in exp) + ' }'
        lines.append('\t{ "%s", "%s", %s, %d, %d, %d, %d, %d, %s },' % (
            name, role, 'F32_M' + shape, r, fault, fr, fc, 0 if exp is None else 1, e))
    lines.append('};')
    return '\n'.join(lines)


def c_twins():
    """The twin table's rows in f32_gate.h: name, shape and the two pinned container paths."""
    return '\n'.join('\t{ "binder_matrix_%d", F32_M%s, "controls/binder_matrix_%d_a.fpo", "controls/binder_matrix_%d_b.fpo" },'
                     % (i, shape, i, i) for i, shape in enumerate(TWINS))


def probe_source(shape, r):
    rows, cols = SHAPES[shape]
    expr = '%s[%d]' % (NAME, r) if cols == 4 else 'float4(%s[%d], 2.5f)' % (NAME, r)
    return ('void main(float4 t : TEXCOORD0, out float4 color : COLOR, uniform float%dx%d %s)\n{\n    color = %s;\n}\n'
            % (rows, cols, NAME, expr))


def embedded_row_words(container, row):
    """The 4 words of the embedded constant slot(s) of `u_matrix[row]` in the container's
    ucode (halfword-swapped on disk), or None when the leaf has no embedded constants."""
    be = lambda o: struct.unpack_from('>I', container, o)[0]
    count, parr, ucode = be(12), be(16), be(28)
    for i in range(count):
        rec = parr + 48 * i
        nm = container[be(rec + 16):container.index(b'\0', be(rec + 16))].decode()
        if nm != '%s[%d]' % (NAME, row):
            continue
        emb = be(rec + 24)
        if not emb:
            return None
        n = be(emb)
        offs = [be(emb + 4 + 4 * j) for j in range(n)]
        words = set()
        for off in offs:
            raw = struct.unpack_from('>4I', container, ucode + off)
            words.add(tuple(((w << 16) | (w >> 16)) & 0xFFFFFFFF for w in raw))
        if len(words) != 1:
            raise SystemExit('u_matrix[%d]: embedded slots disagree %r' % (row, words))
        return list(words.pop())
    return None


def stage(compiler, out):
    ctl = Path(out) / 'controls'
    src = Path(out) / 'src'
    ctl.mkdir(parents=True, exist_ok=True)
    src.mkdir(parents=True, exist_ok=True)
    rows = []
    built = {}
    for name, role, shape, r, fault, fr, fc, exp in recipes():
        key = (shape, r)
        if key not in built:
            s = src / ('mprobe_%s_r%d.fcg' % key)
            s.write_text(probe_source(*key))
            dst = ctl / ('mprobe_%s_r%d.fpo' % key)
            subprocess.run([compiler, '-p', 'sce_fp_rsx', '-e', 'main', '--emit-container', str(dst), str(s)],
                           check=True, capture_output=True)
            built[key] = dst
        path = 'controls/' + built[key].name
        normal = row_words(shape, r)
        if fault == 2:
            emb = embedded_row_words(built[key].read_bytes(), r)
            if emb is None:
                raise SystemExit(name + ': the container has no embedded constants for the skipped row')
            # only the active columns come from the constant slot; a 3-wide probe's
            # fourth lane is the literal pad, whatever the slot holds there
            cols = SHAPES[shape][1]
            exp = emb[:cols] + [PAD] * (4 - cols)
            if exp == normal:
                raise SystemExit(name + ': the embedded words equal the uploaded ones; the skip would be invisible')
        hexw = lambda w: ','.join('%08x' % x for x in w)
        if fault == 0:
            rows.append('B|%s|%s|%s|%s|auto|expect=%s' % (role, name, path, path, hexw(exp)))
        else:
            rows.append('B|%s|%s|%s|%s|auto|expect=%s|normal=%s' % (role, name, path, path, hexw(exp), hexw(normal)))
    # the four mul() integration twins of binder-controls.ps1 (binder_matrix_0..3):
    # side A reads the uniform under auto, side B bakes the same exact values
    for i, (r, c) in enumerate(SHAPES[t] for t in TWINS):
        vec = 'float3(t.xy,.5)' if c == 3 else 'float4(t.xy,.5,1)'
        res = 'mul(%s,%s)' % (NAME, vec)
        if r == 3:
            res = 'float4(%s,1)' % res
        lit = []
        for y in range(r):
            for x in range(c):
                v = struct.unpack('>f', struct.pack('>I', element(y, x)))[0]
                t = '%.9g' % v
                # the decimal literal must round to the very same binary32 word
                assert struct.unpack('>I', struct.pack('>f', float(t)))[0] == element(y, x), 'literal %s does not round-trip' % t
                lit.append(t)
        a = 'void main(float4 t:TEXCOORD0, out float4 color:COLOR, uniform float%dx%d %s){color=%s;}\n' % (r, c, NAME, res)
        b = 'void main(float4 t:TEXCOORD0, out float4 color:COLOR){float%dx%d %s=float%dx%d(%s);color=%s;}\n' % (
            r, c, NAME, r, c, ','.join(lit), res)
        for side, text in (('a', a), ('b', b)):
            s = src / ('binder_matrix_%d_%s.fcg' % (i, side))
            s.write_text(text)
            subprocess.run([compiler, '-p', 'sce_fp_rsx', '-e', 'main', '--emit-container',
                            str(ctl / ('binder_matrix_%d_%s.fpo' % (i, side))), str(s)], check=True, capture_output=True)
        rows.append('B|control-binder-matrix|binder_matrix_%d|controls/binder_matrix_%d_a.fpo|controls/binder_matrix_%d_b.fpo|auto'
                    % (i, i, i))
    return rows


if __name__ == '__main__':
    a = sys.argv[1:]
    if a == ['--recipes']:
        print(c_table())
        print(c_twins())
    elif len(a) == 2 and a[0] == '--check':
        text = Path(a[1]).read_text()
        want = c_table()
        ok = want in text and c_twins() in text
        print('f32_matrix_controls: recipe and twin tables %s' % ('match' if ok else 'DIFFER from the computed ones'))
        sys.exit(0 if ok else 1)
    elif len(a) == 3 and a[0] == '--stage':
        print('\n'.join(stage(a[1], a[2])))
    else:
        sys.exit(__doc__)
